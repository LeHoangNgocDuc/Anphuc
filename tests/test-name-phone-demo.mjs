import assert from 'node:assert/strict';
import {APP_CONFIG} from '../js/config.js';
import {LocalDemoAdapter, SupabaseAdapter} from '../js/db.js';
const demo=await new LocalDemoAdapter(APP_CONFIG).init();
await demo.signOut();
const matches=await demo.searchDemoStudents('nguyen');
assert.ok(matches.some(row=>row.id==='demo-student-001'));
assert.ok(matches.every(row=>!('parent_phone' in row)));
assert.deepEqual(await demo.searchDemoStudents('n'),[]);
await assert.rejects(()=>demo.signInDemoByStudentPhone({studentId:'demo-student-001',phone:'0900000002'}),/khong khop|kh\u00f4ng kh\u1edbp/iu);
let current=await demo.getSession();assert.equal(current.role,'guest');
await demo.signInDemoByStudentPhone({studentId:'demo-student-001',phone:'0900000001'});
current=await demo.getSession();assert.equal(current.role,'parent');
const students=await demo.getStudents();
assert.equal(students.length,1);assert.equal(students[0].id,'demo-student-001');
await assert.rejects(()=>demo.getProgress('demo-student-002'),/quy\u1ec1n|quyền|access/i);
await demo.signOut();assert.equal((await demo.getSession()).role,'guest');
assert.equal(typeof SupabaseAdapter.prototype.searchDemoStudents,'undefined');
assert.equal(typeof SupabaseAdapter.prototype.signInDemoByStudentPhone,'undefined');
console.log('PASS demo name search, exact registered phone match, limited selected student access, guest logout, no live bypass.');
