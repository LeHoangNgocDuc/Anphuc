import assert from 'node:assert/strict';
import {APP_CONFIG} from '../js/config.js';
import {LocalDemoAdapter, SupabaseAdapter} from '../js/db.js';
import {monthlyTuitionRows,dashboardReport,paginateNotices,validatePrintRows} from '../js/teacher-reports.js';

const db=await new LocalDemoAdapter(APP_CONFIG).init();
await db.signOut();
await assert.rejects(()=>db.getUnpaidTuition({month:11,year:2026}),/đăng nhập|quyền/i);
await db.signInTeacher();
let students=await db.getStudents();
assert.equal(students.length,3);
let result=await db.getUnpaidTuition({month:11,year:2026});
assert.equal(result.rows.length,3);
assert.ok(result.rows.every(x=>x.fee_status==='unpaid'&&x.fee_due>0));
await db.saveSetting('tuition_default_amount',650000);
assert.equal((await db.getSettings()).tuition_default_amount,650000);
const s=students.find(x=>x.student_code==='DEMO-001');
assert.ok(s);
const old=await db.saveTuition({studentId:s.id,month:11,year:2026,paid:true,method:'transfer',reference:'ABC-001'});
assert.equal(old.fee_status,'paid');assert.equal(old.paid_amount,old.fee_due);
assert.equal((await db.getUnpaidTuition({month:11,year:2026})).rows.length,2);
const payments=await db.getAttendanceTuition({studentId:s.id,recordType:'tuition',month:11,year:2026});
assert.equal(payments.length,1);
assert.equal(payments[0].payment_reference,'ABC-001');
const reversal=await db.saveTuition({studentId:s.id,month:11,year:2026,paid:false});
assert.equal(reversal.fee_status,'unpaid');assert.equal(reversal.paid_amount,0);
assert.equal((await db.getUnpaidTuition({month:11,year:2026})).rows.length,3);
await assert.rejects(()=>db.saveTuition({studentId:s.id,month:13,year:2026,paid:true}),/Tháng/i);
await db.saveAttendance({studentId:s.id,date:'2026-11-18',attendanceStatus:'present'});
await db.saveAttendance({studentId:s.id,date:'2026-11-18',attendanceStatus:'excused'});
const attendance=(await db.getAttendanceTuition({studentId:s.id,recordType:'attendance'}));
assert.equal(attendance.length,1);
assert.equal(attendance[0].attendance_status,'excused');
const update=await db.saveStudent({student_code:s.student_code,full_name:'Nguyễn Minh An (mẫu)',grade:7,class_name:'7A',parent_phone:'0900000001',custom_fee:600000,active:true});
assert.equal(update.id,s.id);
const newly=await db.saveStudent({student_code:'DEMO-NEW',full_name:'Học sinh thử nghiệm',grade:8,class_name:'8A',parent_phone:'0900000003',custom_fee:'',active:true});
assert.ok(newly.id);
assert.equal((await db.getStudents()).length,4);
const paidRows=monthlyTuitionRows(await db.getStudents(),await db.getAttendanceTuition(),{month:11,year:2026,defaultFee:650000});
assert.equal(paidRows.length,4);
assert.ok(paidRows.find(x=>x.id===newly.id).fee_due===650000);
assert.equal(paidRows.find(x=>x.id===s.id).fee_due,500000); // historical month keeps its recorded fee
const report=dashboardReport(await db.getStudents(),await db.getAllProgress(),await db.getAttendanceTuition(),{month:11,year:2026,defaultFee:650000});
assert.equal(report.summary.students,4);
assert.equal(report.summary.unpaid,4);
assert.equal(report.summary.paid,0);
assert.equal(report.summary.attendance,1);
assert.equal(report.summary.unknown,0);
const grade7=dashboardReport(await db.getStudents(),await db.getAllProgress(),await db.getAttendanceTuition(),{month:11,year:2026,grade:7,defaultFee:650000});
assert.equal(grade7.summary.students,2);
assert.equal(grade7.summary.attendance,1);
const notices=validatePrintRows(paidRows.filter(x=>x.fee_status==='unpaid'));
assert.equal(paginateNotices(notices,'a4').length,2);
assert.equal(paginateNotices(notices,'a5').length,4);
assert.equal(paginateNotices(notices.slice(0,3),'a4').length,2);
assert.throws(()=>validatePrintRows([...notices,notices[0]]),/trùng/);
assert.throws(()=>validatePrintRows([{id:'bad',fee_status:'paid',fee_due:500000}]),/đã đóng/);
await db.setLessonPublished(7, (await db.getLessonCatalog(7))[0].lesson_key,false);
assert.equal((await db.getLessonVisibility()).filter(x=>x.is_published===false).length,1);
console.log('PASS Stage4: staff guard, student upsert, fee config, binary tuition+reversal, attendance idempotency, statistics, print two-up, visibility.');
